#!/usr/bin/env node
/**
 * Pins the published Arabic tafsir source used by the offline reader.
 *
 * Source: spa5k/tafsir_api, edition `ar-tafsir-muyassar` (التفسير الميسر),
 * release v1.2.3. The upstream mirror is MIT-licensed and itself sources the
 * text from TarteelAI's QUL resource 38. This script downloads all 114 surah
 * files, flattens them into one static JSON asset, and writes the SHA-256 into
 * a TypeScript constant so the runtime can refuse a tampered payload.
 *
 * The text is copied verbatim. Nothing here is labelled "reviewed by us".
 */
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const RELEASE = "v1.2.3";
const EDITION = "ar-tafsir-muyassar";
const BASE = `https://cdn.jsdelivr.net/gh/spa5k/tafsir_api@${RELEASE}/tafsir/${EDITION}`;
/* Deliberately fixed: re-running this script for the same release must not
   silently change the pinned bytes. Bump the date only when the release changes. */
const RETRIEVED_AT = "2026-11-23";

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function fetchSurah(surah) {
  for (let attempt = 1; attempt <= 4; attempt += 1) {
    try {
      const res = await fetch(`${BASE}/${surah}.json`);
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const rows = await res.json();
      if (!Array.isArray(rows)) throw new Error("surah payload is not an array");
      return rows;
    } catch (error) {
      if (attempt === 4) throw new Error(`surah ${surah}: ${String(error)}`);
      await sleep(400 * attempt);
    }
  }
  throw new Error("unreachable");
}

const entries = [];
for (let surah = 1; surah <= 114; surah += 1) {
  const rows = await fetchSurah(surah);
  for (const row of rows) {
    if (row?.surah !== surah || !Number.isInteger(row?.ayah)) {
      throw new Error(`surah ${surah}: unexpected row ${JSON.stringify(row).slice(0, 120)}`);
    }
    if (typeof row.text !== "string" || row.text.trim().length === 0) {
      throw new Error(`${surah}:${row.ayah}: empty tafsir text`);
    }
    entries.push({ ref: `${surah}:${row.ayah}`, text: row.text });
  }
  process.stdout.write(`surah ${surah}/114 -> ${entries.length} ayahs\n`);
}

entries.sort((a, b) => {
  const [as, aa] = a.ref.split(":").map(Number);
  const [bs, ba] = b.ref.split(":").map(Number);
  return as - bs || aa - ba;
});
if (entries.length !== 6236) {
  throw new Error(`expected 6236 ayahs, got ${entries.length}`);
}
if (new Set(entries.map((e) => e.ref)).size !== entries.length) {
  throw new Error("duplicate refs in upstream data");
}

const file = {
  version: "1.0.0",
  edition: EDITION,
  editionName: "التفسير الميسر",
  upstream: "spa5k/tafsir_api",
  upstreamVersion: RELEASE,
  upstreamSource: "TarteelAI QUL resource 38 (التفسير الميسر)",
  sourceUrl: "https://github.com/spa5k/tafsir_api",
  dataUrl: BASE,
  license:
    "Static mirror licensed MIT by spa5k/tafsir_api; the tafsir wording belongs to the published التفسير الميسر edition and is redistributed verbatim with attribution. This is not an in-house human review.",
  retrievedAt: RETRIEVED_AT,
  entries,
};
const json = JSON.stringify(file);
const sha256 = createHash("sha256").update(json).digest("hex");

mkdirSync(join(ROOT, "public", "quran"), { recursive: true });
writeFileSync(join(ROOT, "public", "quran", "tafsir-muyassar.json"), json);
writeFileSync(
  join(ROOT, "src", "lib", "quran", "tafsirSource.const.ts"),
  `/* Generated by scripts/download-tafsir-muyassar.mjs — do not edit by hand. */\n` +
    `export const TAFSIR_SOURCE_VERSION = "${file.version}";\n` +
    `export const TAFSIR_SOURCE_SHA256 = "${sha256}";\n` +
    `export const TAFSIR_SOURCE_EDITION = "${EDITION}";\n` +
    `export const TAFSIR_SOURCE_RELEASE = "${RELEASE}";\n` +
    `export const TAFSIR_SOURCE_AYAHS = ${entries.length};\n`
);
const bytes = Buffer.byteLength(json, "utf8");
process.stdout.write(
  `wrote ${entries.length} ayahs, ${json.length} chars / ${bytes} bytes, sha256 ${sha256}\n`
);
