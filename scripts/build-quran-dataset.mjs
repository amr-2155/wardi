import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "public", "quran");

const STANDARD_AYAH_COUNTS = [
  7, 286, 200, 176, 120, 165, 206, 75, 129, 109, 123, 111, 43, 52, 99, 128, 111, 110,
  98, 135, 112, 78, 118, 64, 77, 227, 93, 88, 69, 60, 34, 30, 73, 54, 45, 83, 182,
  88, 75, 85, 54, 53, 89, 59, 37, 35, 38, 29, 18, 45, 60, 49, 62, 55, 78, 96, 29,
  22, 24, 13, 14, 11, 11, 18, 12, 12, 30, 52, 52, 44, 28, 28, 20, 56, 40, 31, 50,
  40, 46, 42, 29, 19, 36, 25, 22, 17, 19, 26, 30, 20, 15, 21, 11, 8, 8, 19, 5, 8,
  8, 11, 11, 8, 3, 9, 5, 4, 7, 3, 6, 3, 5, 4, 5, 6,
];

const VERSES_URL = "https://api.quran.com/api/v4/quran/verses/uthmani";
const CHAPTERS_URL = "https://api.quran.com/api/v4/chapters";

async function fetchJson(url, label) {
  const res = await fetch(url, { headers: { accept: "application/json" } });
  if (!res.ok) throw new Error(`${label} failed: ${res.status} ${res.statusText}`);
  return res.json();
}

async function fetchAllVerses() {
  const data = await fetchJson(VERSES_URL, "verses");
  if (Array.isArray(data.verses) && data.verses.length > 1000) return data.verses;
  if (Array.isArray(data.pagination)) return data.pagination;
  throw new Error("unexpected verses response shape");
}

function sha256Hex(text) {
  return createHash("sha256").update(text, "utf8").digest("hex");
}

const verses = await fetchAllVerses();
const chaptersData = (await fetchJson(CHAPTERS_URL, "chapters")).chapters;

if (verses.length !== 6236) {
  throw new Error(`expected 6236 verses, got ${verses.length}`);
}
if (chaptersData.length !== 114) {
  throw new Error(`expected 114 chapters, got ${chaptersData.length}`);
}

const chapters = [];
const hashes = new Array(6236);
let globalId = 0;
const errors = [];

for (let c = 0; c < 114; c++) {
  const meta = chaptersData.find((ch) => ch.id === c + 1);
  if (!meta) throw new Error(`missing chapter ${c + 1}`);
  const expectedCount = STANDARD_AYAH_COUNTS[c];
  const chapterVerses = verses.filter((v) => v.verse_key.startsWith(`${c + 1}:`));
  if (chapterVerses.length !== expectedCount) {
    errors.push(
      `chapter ${c + 1}: got ${chapterVerses.length} verses, expected ${expectedCount}`
    );
  }
  const verseRecords = chapterVerses
    .map((v) => {
      const number = Number(v.verse_key.split(":")[1]);
      if (!Number.isInteger(number) || number < 1) {
        errors.push(`bad verse_key ${v.verse_key}`);
        return null;
      }
      const text = typeof v.text_uthmani === "string" ? v.text_uthmani.trim() : "";
      if (text.length === 0) {
        errors.push(`empty text ${v.verse_key}`);
      }
      globalId++;
      hashes[globalId - 1] = sha256Hex(text).slice(0, 24);
      return { number, text };
    })
    .filter((v) => v !== null)
    .sort((a, b) => a.number - b.number);

  chapters.push({
    id: c + 1,
    name: meta.name_arabic || "",
    transliteration: meta.name_simple || meta.name_complex || "",
    ayahCount: expectedCount,
    revelationPlace: meta.revelation_place || "",
    verses: verseRecords,
  });
}

if (globalId !== 6236) errors.push(`global counter ended at ${globalId}, expected 6236`);
if (errors.length > 0) {
  console.error("VALIDATION ERRORS:\n" + errors.slice(0, 40).join("\n"));
  process.exit(1);
}

const dataset = {
  manifest: {
    datasetVersion: "1.0.0",
    source: "Quran Foundation (Quran.com) Content API — Uthmani (QCF V2 Madani Mushaf)",
    sourceUrl: VERSES_URL,
    chaptersUrl: CHAPTERS_URL,
    verificationDate: new Date().toISOString().slice(0, 10),
    totalAyahs: 6236,
    chapters: 114,
    licenseNote:
      "Text retrieved from the official Quran.com Content API (Uthmani edition). Displayed verbatim without modification.",
  },
  chapters,
};

mkdirSync(OUT, { recursive: true });
const datasetPath = join(OUT, "quran.json");
const hashesPath = join(OUT, "hashes.json");
writeFileSync(datasetPath, JSON.stringify(dataset), "utf8");
writeFileSync(hashesPath, JSON.stringify(hashes), "utf8");

const bytes = readFileSync(datasetPath);
const datasetSha256 = createHash("sha256").update(bytes).digest("hex");
const sizeKb = (bytes.length / 1024).toFixed(0);

const constPath = join(ROOT, "src", "lib", "quran", "dataset.const.ts");
mkdirSync(dirname(constPath), { recursive: true });
const constContent = [
  "// AUTO-GENERATED by scripts/build-quran-dataset.mjs — do not edit by hand.",
  `export const DATASET_SHA256 = "${datasetSha256}";`,
  `export const QURAN_SOURCE = "${dataset.manifest.source}";`,
  `export const QURAN_SOURCE_URL = "${dataset.manifest.sourceUrl}";`,
  `export const QURAN_DATASET_VERSION = "${dataset.manifest.datasetVersion}";`,
  `export const QURAN_VERIFICATION_DATE = "${dataset.manifest.verificationDate}";`,
  `export const QURAN_TOTAL_AYAHS = ${dataset.manifest.totalAyahs};`,
  "",
].join("\n");
writeFileSync(constPath, constContent, "utf8");

console.log(`written: public/quran/quran.json (${sizeKb} KB)  sha256=${datasetSha256}`);
console.log(`written: public/quran/hashes.json (${(JSON.stringify(hashes).length / 1024).toFixed(0)} KB)`);
console.log(`written: src/lib/quran/dataset.const.ts`);
console.log(`total verses: ${globalId} | chapters: ${chapters.length}`);
