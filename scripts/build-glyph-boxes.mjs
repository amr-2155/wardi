/**
 * Precompute tight per-page glyph boxes for all 604 mushaf scans.
 *
 * Why: the on-device canvas measurement was fragile (transparent-margin
 * exports, conservative guards) and never tighter than the baked alpha box.
 * Measuring once offline with an adaptive paper-tone threshold gives every
 * page its exact ink bounding box, so the reader can width-fill each page
 * maximally with zero runtime cost and zero risk of clipping.
 *
 * Usage: node scripts/build-glyph-boxes.mjs
 * Output: src/lib/quran/glyphBoxes.ts
 */
import sharp from "sharp";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const PAGES_DIR = path.join(root, "public", "quran", "pages");
const OUT_FILE = path.join(root, "src", "lib", "quran", "glyphBoxes.ts");

const PAGE_W = 1024;
const PAGE_H = 1656;
const TOTAL = 604;

async function loadRaw(page) {
  const { data, info } = await sharp(path.join(PAGES_DIR, `${page}.webp`))
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  if (info.width !== PAGE_W || info.height !== PAGE_H) {
    throw new Error(`page ${page}: unexpected size ${info.width}x${info.height}`);
  }
  return data;
}

function luminance(data, i) {
  return (data[i] + data[i + 1] + data[i + 2]) / 3;
}

/** Median paper tone from opaque pixels (adaptive per page). */
function paperTone(data) {
  const samples = [];
  for (let y = 0; y < PAGE_H; y += 6) {
    for (let x = 0; x < PAGE_W; x += 6) {
      const i = (y * PAGE_W + x) * 4;
      if (data[i + 3] > 32) samples.push(luminance(data, i));
    }
  }
  if (samples.length === 0) return 235;
  samples.sort((a, b) => a - b);
  return samples[Math.floor(samples.length / 2)];
}

function makeInk(data, threshold) {
  return (x, y) => {
    const i = (y * PAGE_W + x) * 4;
    return data[i + 3] > 32 && luminance(data, i) < threshold;
  };
}

/** Tight ink box with density rule (robust to specks/edge noise). */
function tightBox(ink) {
  const rowHits = (y) => {
    let n = 0;
    for (let x = 0; x < PAGE_W; x += 2) if (ink(x, y)) n++;
    return n;
  };
  const colHits = (x) => {
    let n = 0;
    for (let y = 0; y < PAGE_H; y += 2) if (ink(x, y)) n++;
    return n;
  };
  const ROW_MIN = 3;
  const COL_MIN = 4;
  let t = 0;
  while (t < PAGE_H && rowHits(t) < ROW_MIN) t += 2;
  let b = PAGE_H - 1;
  while (b > t && rowHits(b) < ROW_MIN) b -= 2;
  let l = 0;
  while (l < PAGE_W && colHits(l) < COL_MIN) l += 2;
  let r = PAGE_W - 1;
  while (r > l && colHits(r) < COL_MIN) r -= 2;
  if (l >= r || t >= b) return null;
  return [l, t, r, b];
}

async function boxFor(page) {
  const data = await loadRaw(page);
  const paper = paperTone(data);
  // Ink = clearly darker than this page's own paper (catches black text as
  // well as dark/red/green ornament inks, ignores paper texture).
  const threshold = Math.max(110, paper - 30);
  let box = tightBox(makeInk(data, threshold));
  let method = "ink";
  const area = box ? (box[2] - box[0]) * (box[3] - box[1]) : 0;
  if (!box || area < PAGE_W * PAGE_H * 0.3) {
    // Fallback: pure-alpha box (fully transparent margins).
    const alphaInk = (x, y) => data[(y * PAGE_W + x) * 4 + 3] > 32;
    box = tightBox(alphaInk) ?? [0, 0, PAGE_W - 1, PAGE_H - 1];
    method = "alpha";
  }
  return { box, method, paper: Math.round(paper) };
}

const boxes = {};
const stats = { ink: 0, alpha: 0, minRatio: Infinity, maxRatio: 0 };
for (let p = 1; p <= TOTAL; p++) {
  const { box, method, paper } = await boxFor(p);
  boxes[p] = box;
  stats[method]++;
  const ratio = (box[3] - box[1]) / Math.max(1, box[2] - box[0]);
  stats.minRatio = Math.min(stats.minRatio, ratio);
  stats.maxRatio = Math.max(stats.maxRatio, ratio);
  if (method === "alpha") console.log(`page ${p}: alpha fallback (paper ${paper})`);
  if (p % 100 === 0) console.log(`... ${p}/${TOTAL}`);
}

const entries = Object.entries(boxes)
  .map(([k, v]) => `  ${k}: [${v.join(", ")}],`)
  .join("\n");

const out = `/**
 * Precomputed tight glyph boxes for the 604 mushaf page scans.
 * Generated by scripts/build-glyph-boxes.mjs — DO NOT EDIT BY HAND.
 * Format: page -> [left, top, right, bottom] in 1024x1656 source pixels.
 * The box bounds ALL ink (text, headers, markers, ornaments); the reader
 * width-fills this box, so every page renders maximally with no clipping.
 */
export const GLYPH_PAGE_W = ${PAGE_W};
export const GLYPH_PAGE_H = ${PAGE_H};

export const GLYPH_BOXES: Record<number, [number, number, number, number]> = {
${entries}
};
`;

fs.writeFileSync(OUT_FILE, out);
console.log(`wrote ${OUT_FILE}`);
console.log(`methods: ${JSON.stringify({ ink: stats.ink, alpha: stats.alpha })}`);
console.log(`box ratio range: ${stats.minRatio.toFixed(3)} .. ${stats.maxRatio.toFixed(3)}`);
