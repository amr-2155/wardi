const LOCALES: Record<Locale, Record<string, string>> = { ar: AR, en: EN };

const STORAGE_KEY = "ward:v2:locale";

function detectLocale(): Locale {
  if (typeof navigator !== "undefined") {
    const lang = navigator.language || "";
    if (lang.startsWith("ar")) return "ar";
  }
  return "en";
}

export function getLocaleFromStorage(): Locale {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "ar" || saved === "en") return saved;
  } catch { /* ignore */ }
  return detectLocale();
}

export function saveLocaleToStorage(locale: Locale): void {
  try {
    localStorage.setItem(STORAGE_KEY, locale);
  } catch { /* ignore */ }
}

export function t(locale: Locale, key: string, params?: Record<string, string | number>): string {
  const dict = LOCALES[locale];
  let value = dict[key] ?? LOCALES.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      value = value.replaceAll(`{{${k}}}`, String(v));
    }
  }
  return value;
}

export const WEEKDAYS_AR = ["السبت", "الأحد", "الاثنين", "الثلاثاء", "الأربعاء", "الخميس", "الجمعة"];
export const WEEKDAYS_EN = ["Sat", "Sun", "Mon", "Tue", "Wed", "Thu", "Fri"];

export function getWeekdayShort(locale: Locale, date: Date): string {
  const names = locale === "ar" ? WEEKDAYS_AR : WEEKDAYS_EN;
  const day = date.getDay();
  const idx = locale === "ar" ? (day + 1) % 7 : (day === 0 ? 0 : day === 6 ? 0 : day);
  return names[idx];
}

export function getWeekStart(locale: Locale, today: Date): Date {
  const d = new Date(today);
  d.setHours(0, 0, 0, 0);
  if (locale === "ar") {
    const day = d.getDay();
    const satOffset = (day + 1) % 7;
    d.setDate(d.getDate() - satOffset);
  } else {
    const day = d.getDay();
    d.setDate(d.getDate() - day);
  }
  return d;
}

export function formatLocaleDate(locale: Locale, key: string): string {
  const d = new Date(`${key}T00:00:00`);
  return d.toLocaleDateString(locale === "ar" ? "ar-EG" : "en-US", {
    weekday: "long",
    day: "numeric",
    month: "long",
  });
}

export function formatLocaleShort(locale: Locale, key: string): string {
  const d = new Date(`${key}T00:00:00`);
  return d.toLocaleDateString(locale === "ar" ? "ar-EG" : "en-US", {
    day: "numeric",
    month: "short",
  });
}

export type LocaleContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string, params?: Record<string, string | number>) => string;
};

import { createContext, useContext } from "react";

export const LocaleContext = createContext<LocaleContextValue>({
  locale: "ar",
  setLocale: () => {},
  t: (key) => key,
});

export function useLocale(): LocaleContextValue {
  return useContext(LocaleContext);
}

export function useLocaleState(): LocaleContextValue {
  const [locale, setLocaleRaw] = useState<Locale>("ar");
  const [loaded, setLoaded] = useState(false);

  useEffect(() => {
    setLocale(getLocaleFromStorage());
    setLoaded(true);
  }, []);

  const setLocale = useCallback((l: Locale) => {
    setLocaleRaw(l);
    saveLocaleToStorage(l);
    document.documentElement.lang = l;
    document.documentElement.dir = l === "ar" ? "rtl" : "ltr";
  }, []);

  useEffect(() => {
    if (loaded) {
      document.documentElement.lang = locale;
      document.documentElement.dir = locale === "ar" ? "rtl" : "ltr";
    }
  }, [locale, loaded]);

  const tFn = useCallback(
    (key: string, params?: Record<string, string | number>) => t(locale, key, params),
    [locale]
  );

  return useMemo(() => ({ locale, setLocale, t: tFn }), [locale, setLocale, tFn]);
}
