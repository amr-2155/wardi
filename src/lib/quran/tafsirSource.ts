import { validateRichTafsirEntry } from "../tafsir/core";
import type { RichTafsirEntry } from "../tafsir/types";
import { sha256Text } from "./validate";
import {
  TAFSIR_SOURCE_AYAHS,
  TAFSIR_SOURCE_EDITION,
  TAFSIR_SOURCE_RELEASE,
  TAFSIR_SOURCE_SHA256,
  TAFSIR_SOURCE_VERSION,
} from "./tafsirSource.const";

/**
 * Offline loader for the published التفسير الميسر pack.
 *
 * The JSON lives in `public/`, not in the JS bundle: the reader only downloads
 * it when an ayah screen opens, and the pinned SHA-256 is checked before any of
 * its text is parsed or shown. The fetch starts in a React effect (see the
 * hook), never during render. Nothing here contacts the upstream CDN at
 * runtime — regenerating the asset is an explicit maintainer action.
 */

export const TAFSIR_SOURCE_PATH = "/quran/tafsir-muyassar.json";

export const TAFSIR_SOURCE_META = {
  path: TAFSIR_SOURCE_PATH,
  version: TAFSIR_SOURCE_VERSION,
  edition: TAFSIR_SOURCE_EDITION,
  release: TAFSIR_SOURCE_RELEASE,
  ayahs: TAFSIR_SOURCE_AYAHS,
  sha256: TAFSIR_SOURCE_SHA256,
} as const;

type SourceRow = { ref?: unknown; text?: unknown };
type SourceFile = {
  version?: unknown;
  edition?: unknown;
  editionName?: unknown;
  upstream?: unknown;
  upstreamVersion?: unknown;
  upstreamSource?: unknown;
  sourceUrl?: unknown;
  license?: unknown;
  retrievedAt?: unknown;
  entries?: unknown;
};

const isNonEmptyString = (value: unknown): value is string =>
  typeof value === "string" && value.trim().length > 0;

const isIsoDate = (value: unknown): value is string =>
  isNonEmptyString(value) && /^\d{4}-\d{2}-\d{2}$/.test(value);

/** True only for the exact bytes generated by the pinned downloader. */
export async function verifyPublishedTafsirText(text: string): Promise<boolean> {
  return (await sha256Text(text)) === TAFSIR_SOURCE_SHA256;
}

/**
 * Pure mapping, separated from I/O so the engine harness can assert the shape
 * without stubbing `fetch`. Returns null for any structural problem: a pinned
 * file must be complete, not partly rendered.
 */
export function mapPublishedTafsir(raw: unknown): RichTafsirEntry[] | null {
  if (typeof raw !== "object" || raw === null) return null;
  const file = raw as SourceFile;
  if (file.version !== TAFSIR_SOURCE_VERSION) return null;
  if (file.edition !== TAFSIR_SOURCE_EDITION) return null;
  if (!isNonEmptyString(file.editionName)) return null;
  if (!isNonEmptyString(file.upstream)) return null;
  if (file.upstreamVersion !== TAFSIR_SOURCE_RELEASE) return null;
  if (!isNonEmptyString(file.upstreamSource)) return null;
  if (!isNonEmptyString(file.sourceUrl)) return null;
  if (!isNonEmptyString(file.license)) return null;
  if (!isIsoDate(file.retrievedAt)) return null;
  if (!Array.isArray(file.entries) || file.entries.length !== TAFSIR_SOURCE_AYAHS) {
    return null;
  }

  const seen = new Set<string>();
  const entries: RichTafsirEntry[] = [];
  for (const row of file.entries as SourceRow[]) {
    if (typeof row !== "object" || row === null) return null;
    if (typeof row.ref !== "string" || !/^\d{1,3}:\d{1,3}$/.test(row.ref)) return null;
    if (!isNonEmptyString(row.text)) return null;
    if (seen.has(row.ref)) return null;
    seen.add(row.ref);

    /* The upstream text is copied verbatim into `detailed`; only the blank
       line/single line separators become paragraph boundaries. No section is
       added, summarized, or reworded. */
    const paragraphs = row.text
      .split(/\r?\n/)
      .map((line) => line.trim())
      .filter(Boolean);
    const entry: RichTafsirEntry = {
      ref: row.ref as RichTafsirEntry["ref"],
      reviewStatus: "published",
      sourceDate: file.retrievedAt,
      sourceEdition: `${file.editionName} (${TAFSIR_SOURCE_EDITION} ${TAFSIR_SOURCE_RELEASE})`,
      detailed: paragraphs.length > 0 ? paragraphs : [row.text],
    };
    if (!validateRichTafsirEntry(entry)) return null;
    entries.push(entry);
  }
  return entries;
}

let cached: RichTafsirEntry[] | null = null;
let inFlight: Promise<RichTafsirEntry[] | null> | null = null;

/**
 * Hash-gated load of the static asset. A verified pack is cached for the whole
 * session and concurrent callers share one request. Failures are NOT cached:
 * a transient WebView/fetch glitch can be retried on the next ayah. A failed or
 * tampered payload resolves to null rather than throwing into render or showing
 * unverified text.
 */
export function loadPublishedTafsir(): Promise<RichTafsirEntry[] | null> {
  if (cached) return Promise.resolve(cached);
  if (!inFlight) {
    const task = (async () => {
      try {
        const res = await fetch(TAFSIR_SOURCE_PATH);
        if (!res.ok) return null;
        const text = await res.text();
        if (!(await verifyPublishedTafsirText(text))) return null;
        const mapped = mapPublishedTafsir(JSON.parse(text) as unknown);
        if (mapped) cached = mapped;
        return mapped;
      } catch {
        return null;
      }
    })();
    inFlight = task.finally(() => {
      inFlight = null;
    });
  }
  return inFlight;
}
